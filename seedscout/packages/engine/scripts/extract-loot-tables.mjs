#!/usr/bin/env node
// Downloads a Minecraft server jar from Mojang's launcher metadata and extracts
// data/minecraft/loot_table/chests/*.json into src/loot/tables.generated.ts.
//
//   node scripts/extract-loot-tables.mjs 1.21=1.21.4 1.20=1.20.6
//
// Left side: our McVersion key. Right side: the exact game release to extract.
// Requires `unzip`. The output is git-ignored-worthy Mojang data: review your
// distribution rights before committing it.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "../src/loot/tables.generated.ts");
const pairs = process.argv.slice(2).map((a) => a.split("="));
if (!pairs.length) {
  console.error("usage: extract-loot-tables.mjs <key>=<release> ...");
  process.exit(1);
}

const manifest = await (await fetch("https://piston-meta.mojang.com/mc/game/version_manifest_v2.json")).json();
const result = {};
for (const [key, release] of pairs) {
  const entry = manifest.versions.find((v) => v.id === release);
  if (!entry) throw new Error(`unknown release ${release}`);
  const meta = await (await fetch(entry.url)).json();
  const dir = mkdtempSync(join(tmpdir(), "loot-"));
  const jar = join(dir, "server.jar");
  writeFileSync(jar, Buffer.from(await (await fetch(meta.downloads.server.url)).arrayBuffer()));
  // Since 1.18 the server jar is a bundler; the real jar is nested under META-INF/versions.
  execFileSync("unzip", ["-q", "-o", jar, "-d", dir]);
  const nested = join(dir, "META-INF/versions", release, `server-${release}.jar`);
  const inner = join(dir, "inner");
  execFileSync("unzip", ["-q", "-o", existsSync(nested) ? nested : jar, "data/minecraft/loot_table*/chests/*", "-d", inner]);
  const base = ["loot_table", "loot_tables"].map((d) => join(inner, "data/minecraft", d)).find(existsSync);
  const tables = {};
  const walk = (d, prefix) => {
    for (const f of readdirSync(d, { withFileTypes: true })) {
      if (f.isDirectory()) walk(join(d, f.name), `${prefix}${f.name}/`);
      else if (f.name.endsWith(".json")) tables[`${prefix}${f.name.slice(0, -5)}`] = JSON.parse(readFileSync(join(d, f.name), "utf8"));
    }
  };
  walk(join(base, "chests"), "chests/");
  result[key] = tables;
  console.log(`${key} (${release}): ${Object.keys(tables).length} chest tables`);
}

writeFileSync(
  out,
  `// Generated by scripts/extract-loot-tables.mjs. Do not edit by hand.
import type { LootTable } from "./roll";
import type { McVersion } from "../versions";

export const LOOT_TABLES: Partial<Record<McVersion, Record<string, LootTable>>> = ${JSON.stringify(result)};
`,
);
